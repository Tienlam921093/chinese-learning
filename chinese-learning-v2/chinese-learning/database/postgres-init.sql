CREATE TABLE IF NOT EXISTS Users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL, email VARCHAR(200) NOT NULL,
  password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'student',
  hsk_level SMALLINT NOT NULL DEFAULT 1 CHECK (hsk_level BETWEEN 1 AND 6),
  xp INTEGER NOT NULL DEFAULT 0, streak INTEGER NOT NULL DEFAULT 0,
  last_login TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, is_active BOOLEAN NOT NULL DEFAULT TRUE,
  avatar_url VARCHAR(500), oauth_provider VARCHAR(20), oauth_provider_id VARCHAR(100),
  oauth_display_name VARCHAR(100), token_version INTEGER NOT NULL DEFAULT 1,
  password_changed_at TIMESTAMPTZ, plan VARCHAR(20) NOT NULL DEFAULT 'free', plan_expiry TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS Lessons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, hsk_level SMALLINT NOT NULL CHECK (hsk_level BETWEEN 1 AND 6),
  title VARCHAR(200) NOT NULL, description VARCHAR(500), content TEXT, emoji VARCHAR(50),
  word_count INTEGER NOT NULL DEFAULT 0, duration_minutes INTEGER NOT NULL DEFAULT 15,
  order_index INTEGER NOT NULL DEFAULT 0, is_published BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Vocabulary (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, lesson_id INTEGER REFERENCES Lessons(id) ON DELETE SET NULL,
  hsk_level SMALLINT NOT NULL, hanzi VARCHAR(50) NOT NULL, pinyin VARCHAR(100) NOT NULL,
  meaning VARCHAR(300) NOT NULL, meaning_en VARCHAR(300), example VARCHAR(500),
  example_pinyin VARCHAR(500), example_meaning VARCHAR(500), audio_url VARCHAR(500),
  tone SMALLINT, category VARCHAR(50), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS UserProgress (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  lesson_id INTEGER NOT NULL REFERENCES Lessons(id) ON DELETE CASCADE, completed BOOLEAN NOT NULL DEFAULT FALSE,
  score INTEGER, time_spent INTEGER, attempts INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, lesson_id)
);

CREATE TABLE IF NOT EXISTS VocabReviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  vocab_id INTEGER NOT NULL REFERENCES Vocabulary(id) ON DELETE CASCADE, quality SMALLINT NOT NULL,
  ease_factor DOUBLE PRECISION NOT NULL DEFAULT 2.5, interval_days INTEGER NOT NULL DEFAULT 1,
  repetitions INTEGER NOT NULL DEFAULT 0, next_review TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE (user_id, vocab_id)
);

CREATE TABLE IF NOT EXISTS ChatHistory (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  user_message TEXT NOT NULL, bot_reply TEXT NOT NULL, mode VARCHAR(20) NOT NULL DEFAULT 'free',
  ai_provider VARCHAR(20), tokens_used INTEGER, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS QuizResults (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  lesson_id INTEGER REFERENCES Lessons(id), total_questions INTEGER NOT NULL, correct_answers INTEGER NOT NULL,
  score DOUBLE PRECISION GENERATED ALWAYS AS (correct_answers::DOUBLE PRECISION / NULLIF(total_questions, 0) * 100) STORED,
  time_taken INTEGER, quiz_type VARCHAR(20), xp_awarded INTEGER NOT NULL DEFAULT 0, attempt_key VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS RefreshTokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token_hash VARCHAR(128) NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE, expires_at TIMESTAMPTZ NOT NULL,
  revoked BOOLEAN NOT NULL DEFAULT FALSE, revoked_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_agent VARCHAR(500), ip_address VARCHAR(45)
);

CREATE TABLE IF NOT EXISTS PasswordResets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
  token_hash VARCHAR(128) NOT NULL UNIQUE, expires_at TIMESTAMPTZ NOT NULL, used BOOLEAN NOT NULL DEFAULT FALSE,
  used_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, ip_address VARCHAR(45)
);

CREATE TABLE IF NOT EXISTS Orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id VARCHAR(50) NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE, plan VARCHAR(20) NOT NULL,
  amount INTEGER NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending', payment_method VARCHAR(20),
  paid_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS LiveClasses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES Users(id),
  title VARCHAR(160) NOT NULL, description VARCHAR(1000), hsk_level SMALLINT NOT NULL CHECK (hsk_level BETWEEN 1 AND 6),
  starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL, meeting_url VARCHAR(500) NOT NULL,
  meeting_platform VARCHAR(20) NOT NULL DEFAULT 'other', capacity INTEGER NOT NULL DEFAULT 30 CHECK (capacity BETWEEN 1 AND 500),
  status VARCHAR(20) NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','cancelled','completed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS LiveClassEnrollments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, class_id INTEGER NOT NULL REFERENCES LiveClasses(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES Users(id) ON DELETE CASCADE, status VARCHAR(20) NOT NULL DEFAULT 'enrolled'
    CHECK (status IN ('enrolled','cancelled')), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE (class_id, user_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_password ON Users(email)
  WHERE password_hash IS NOT NULL AND password_hash <> 'OAUTH_NO_PASSWORD';
CREATE INDEX IF NOT EXISTS ix_users_oauth ON Users(oauth_provider, oauth_provider_id) WHERE oauth_provider IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_vocab_hsk ON Vocabulary(hsk_level);
CREATE INDEX IF NOT EXISTS ix_progress_user ON UserProgress(user_id);
CREATE INDEX IF NOT EXISTS ix_reviews_due ON VocabReviews(user_id, next_review);
CREATE INDEX IF NOT EXISTS ix_chat_user ON ChatHistory(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_refresh_user ON RefreshTokens(user_id);
CREATE INDEX IF NOT EXISTS ix_orders_user ON Orders(user_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ux_quiz_attempt_key ON QuizResults(attempt_key) WHERE attempt_key IS NOT NULL;

